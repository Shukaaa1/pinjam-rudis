// Helper to find student by username or NIM
function findStudentByCredentials(usernameOrNim) {
    if (!usernameOrNim) return null;
    const clean = usernameOrNim.trim().toLowerCase();
    return DUMMY_STUDENTS.find(s => 
        s.username.toLowerCase() === clean || 
        s.nim.toLowerCase() === clean ||
        s.email.toLowerCase().startsWith(clean)
    ) || null;
}

